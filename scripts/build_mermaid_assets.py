#!/usr/bin/env python3
"""Maintainer: freeze canonical styles for the offline Mermaid extension."""
import hashlib
import json
from pathlib import Path
from drawio_assets import default_profile

ROOT=Path(__file__).resolve().parents[1]


def main():
    source=ROOT/'assets/drawio-c4/native-templates.json'
    value=json.loads(source.read_text(encoding='utf-8'))
    data={'source_sha256':value['source_sha256'],'template_sha256':hashlib.sha256(source.read_bytes()).hexdigest(),'entries':{entry['name']:entry for entry in value['entries']},'palette':default_profile()}
    with (ROOT/'assets/offline/drawio-data.js').open('w',encoding='utf-8',newline='\n') as output:
        output.write('/* Frozen canonical asset data; generated by scripts/build_mermaid_assets.py. */\nwindow.C4_DRAWIO_DATA = '+json.dumps(data,ensure_ascii=True,separators=(',',':'))+';\n')
    print('Exact Mermaid asset data built from the supplied palette.')


if __name__=='__main__':main()
